import { describe, expect, it } from 'vitest';
import { applySourceFixes, normaliseSource } from '../../../scripts/content/discover';
import { IssueCollector, formatIssue } from '../../../scripts/content/errors';
import { buildDoc } from '../../../scripts/content/meta';
import type { Block } from '../../../src/lib/content/schema';
import { afMarkers, codes, enMarkers, parseMd, readCorpus, realEntry } from './helpers';

const kinds = (blocks: readonly Block[]): string[] =>
  blocks.map((block) => `${block.id}:${block.kind}`);

function footerOf(id: string): string {
  const source = readCorpus(realEntry(id));
  const start = source.lastIndexOf('\n---\n');
  return source.slice(start);
}

describe('footer', () => {
  it.each([
    ['core/register', '2026-09-13', 'links to ../05 and ../00'],
    ['lookup/glossary', '2026-09-13', 'links inside the Look it up folder'],
    ['start/how-to-use', '2026-09-13', 'links inside the Start here folder'],
    ['core/you-are-the-business', '2026-09-14', 'dated 14 September'],
  ])('strips the %s footer (%s, %s) into doc.generated', (id, date) => {
    const entry = realEntry(id, {
      kind: 'guide',
      hideSections: undefined,
      blockOverrides: undefined,
      fenceOverrides: undefined,
    });
    const { parsed, issues } = parseMd(`# Title\n\nBody text.\n\n${footerOf(id)}`, entry);
    expect(codes(issues)).toEqual([]);
    expect(parsed.generated).toEqual({ date, tool: 'Claude, Anthropic' });
    expect(kinds(parsed.blocks)).toEqual(['intro.1:paragraph']);
  });

  it('keeps documents without a footer intact', () => {
    const { parsed, issues } = parseMd(
      '# QUOTATION\n\nBody.\n\n---\n\n*Fill this in.*\n',
      realEntry('paperwork/templates/quotation'),
    );
    expect(codes(issues)).toEqual([]);
    expect(parsed.generated).toBeUndefined();
    expect(kinds(parsed.blocks)).toEqual(['intro.1:paragraph', 'intro.2:hr', 'intro.3:note']);
  });

  it.each([
    [
      '# T\n\nBody.\n\n*Generated by AI (Claude, Anthropic) on 13 September 2026.*\n',
      'footer-without-rule',
    ],
    [
      '# T\n\n*Generated by AI (Claude, Anthropic) on 13 September 2026.*\n\nMore.\n',
      'footer-misplaced',
    ],
    ['# T\n\nBody.\n\n---\n\n*Generated by AI at some point.*\n', 'footer-unparsed'],
  ])('reports a malformed footer: %j', (markdown, code) => {
    expect(codes(parseMd(markdown, realEntry('core/register')).issues)).toContain(code);
  });
});

describe('words used in this file', () => {
  const markdown = [
    '# Tax',
    '',
    'Intro.',
    '',
    '## Words used in this file',
    '',
    'Plain meanings. The full list is in [Glossary](../05%20Look%20it%20up/01-glossary.md).',
    '',
    '| Word | Meaning |',
    '|---|---|',
    '| IRP6 | The **short** form. |',
    '| VAT | 15% tax. |',
    '',
    '## Next',
    '',
    'Text.',
  ].join('\n');

  it('becomes a terms block and doc.terms', () => {
    const { parsed, issues } = parseMd(markdown, realEntry('core/tax-and-sars'));
    expect(codes(issues)).toEqual([]);
    expect(kinds(parsed.blocks)).toEqual([
      'intro.1:paragraph',
      'words-used-in-this-file:heading',
      'words-used-in-this-file.1:terms',
      'next:heading',
      'next.1:paragraph',
    ]);
    const doc = buildDoc(
      parsed,
      { status: 'source', sourceLang: 'en' },
      {
        sources: { entries: [], acts: [] },
        generated: { date: '2026-09-13', tool: 'Claude (Anthropic)' },
        verification: { status: 'ai-checked', checkedOn: '2026-09-13' },
      },
    );
    expect(doc.generated).toEqual({ date: '2026-09-13', tool: 'Claude (Anthropic)' });
    expect(doc.terms).toEqual([
      { term: 'IRP6', meaning: 'The short form.' },
      { term: 'VAT', meaning: '15% tax.' },
    ]);
    expect(parsed.links).toEqual([
      {
        from: 'core/tax-and-sars',
        block: 'words-used-in-this-file.1',
        doc: 'lookup/glossary',
        anchor: undefined,
      },
    ]);
  });

  it('reports a heading that is not followed by an intro and a two-column table', () => {
    expect(
      codes(
        parseMd('# T\n\n## Words used in this file\n\n- a list\n', realEntry('core/tax-and-sars'))
          .issues,
      ),
    ).toEqual(['terms-structure']);
    expect(
      codes(
        parseMd(
          '# T\n\n## Words used in this file\n\nIntro.\n\n| A | B | C |\n|---|---|---|\n| 1 | 2 | 3 |\n',
          realEntry('core/tax-and-sars'),
        ).issues,
      ),
    ).toEqual(['terms-structure']);
  });
});

describe('pseudo headings', () => {
  const checklist =
    '# Master checklist\n\n## Part B\n\n**Before you trade**\n- [ ] One\n\n**Vehicle dealer** (`04-business-types/01`)\n- [ ] BRNC\n';

  it('promotes bold-only lines to depth-4 headings and captures the ref', () => {
    const { parsed, issues } = parseMd(checklist, realEntry('lookup/checklist'));
    expect(codes(issues)).toEqual([]);
    expect(kinds(parsed.blocks)).toEqual([
      'part-b:heading',
      'before-you-trade:heading',
      'before-you-trade.1:tasklist',
      'vehicle-dealer:heading',
      'vehicle-dealer.1:tasklist',
    ]);
    const dealer = parsed.blocks[3];
    expect(
      dealer?.kind === 'heading' && {
        depth: dealer.depth,
        pseudo: dealer.pseudo,
        ref: dealer.ref,
        text: dealer.text,
      },
    ).toEqual({
      depth: 4,
      pseudo: true,
      ref: 'business-types/vehicle-dealer',
      text: 'Vehicle dealer',
    });
    expect(parsed.legacy).toEqual([
      {
        doc: 'lookup/checklist',
        block: 'vehicle-dealer',
        code: '04-business-types/01',
        target: 'business-types/vehicle-dealer',
      },
    ]);
  });

  it('reports a ref that does not resolve to a document', () => {
    expect(
      codes(
        parseMd('# T\n\n**Folder** (`04-business-types/`)\n', realEntry('lookup/checklist')).issues,
      ),
    ).toEqual(['pseudo-heading-ref']);
  });

  it.each([
    ['paperwork/templates/quotation', 'a template'],
    ['lookup/sources', 'the sources register'],
  ])('does not promote bold-only lines in %s (%s)', (id) => {
    const { parsed } = parseMd('# T\n\n**[YOUR BUSINESS NAME]**\n', realEntry(id));
    expect(parsed.blocks.map((block) => block.kind)).toEqual(['paragraph']);
  });
});

