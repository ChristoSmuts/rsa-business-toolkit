describe('source normalisation', () => {
  it('parses CRLF exactly like LF', () => {
    const source = readCorpus(realEntry('business-types/food'));
    const lf = parseMd(source, realEntry('business-types/food')).parsed;
    const crlf = parseMd(source.replace(/\n/g, '\r\n'), realEntry('business-types/food')).parsed;
    expect(crlf.blocks).toEqual(lf.blocks);
    expect(crlf.contentHash).toBe(lf.contentHash);
  });

  it('strips a leading byte-order mark and nothing else', () => {
    expect(normaliseSource(`${String.fromCharCode(0xfeff)}# T\r\nFEFF stays\r`)).toBe(
      '# T\nFEFF stays\n',
    );
  });

  it('applies a source fix only when it matches exactly once', () => {
    const issues = new IssueCollector();
    const entry = realEntry('core/start-here');
    const fixed = applySourceFixes(
      'x\nthe habits that stop you being scammed.\n3. Pick a name',
      entry,
      'en',
      enMarkers(),
      issues,
    );
    expect(fixed).toContain('scammed.\n\n3. Pick');
    expect(applySourceFixes('no match here', entry, 'en', enMarkers(), issues)).toBe(
      'no match here',
    );
    expect(applySourceFixes('no match here', entry, 'af', afMarkers(), issues)).toBe(
      'no match here',
    );
    expect(codes(issues)).toEqual(['source-fix']);
  });

  it('fixes the start-here list quirk in a translation, with or without the blank line already there', () => {
    const entry = realEntry('core/start-here');
    const issues = new IssueCollector();
    const copied =
      '# Begin\n\n## Volgorde\n\n1. Verkoop iets.\n2. Maak ’n bankrekening oop.\n\n As jy van die huis af werk, lees eers dit.\n3. Kies ’n naam.\n4. Maak sjablone.\n';
    const fixed = applySourceFixes(copied, entry, 'af', afMarkers(), issues);
    expect(fixed).toContain('lees eers dit.\n\n3. Kies');
    expect(applySourceFixes(fixed, entry, 'af', afMarkers(), issues)).toBe(fixed);
    const unindented = copied.replace('\n As jy', '\nAs jy');
    expect(applySourceFixes(unindented, entry, 'af', afMarkers(), issues)).toContain(
      'dit.\n\n3. Kies',
    );
    // Anchored to the "2. " line: another note directly above a "3. " elsewhere is left alone.
    const elsewhere = `${fixed}\n## Nog iets\n\n Die drie dinge:\n3. Derde ding.\n`;
    expect(applySourceFixes(elsewhere, entry, 'af', afMarkers(), issues)).toBe(elsewhere);
    expect(codes(issues)).toEqual([]);
    expect(kinds(parseMd(fixed, entry, 'af').parsed.blocks)).toEqual([
      'volgorde:heading',
      'volgorde.1:list',
      'volgorde.2:paragraph',
      'volgorde.3:list',
    ]);
    const twice = `${copied}\n2. Weer ’n stap.\n\n Nog ’n nota.\n3. Weer.\n`;
    applySourceFixes(twice, entry, 'af', afMarkers(), issues);
    applySourceFixes(fixed, entry, 'en', enMarkers(), issues);
    expect(issues.issues.map((issue) => issue.message)).toEqual([
      'expected at most one match for the sourceFixes pattern "^(2\\\\. [^\\\\n]*\\\\n\\\\n?)( ?[^\\\\s\\\\d-][^\\\\n]*)\\\\n(3\\\\. )", found 2',
      'expected exactly one match for a sourceFixes "find", found 0',
    ]);
  });

  it('refuses a source fix that would change a fact', () => {
    const issues = new IssueCollector();
    const entry = {
      ...realEntry('core/start-here'),
      sourceFixes: [
        {
          lang: 'en' as const,
          find: 'pay R100',
          replace: 'pay R200',
          reason: 'A fix that changes an amount, which the guard must refuse.',
        },
      ],
    };
    expect(applySourceFixes('You pay R100 once.', entry, 'en', enMarkers(), issues)).toBe(
      'You pay R100 once.',
    );
    expect(issues.issues.map((issue) => issue.message)).toEqual([
      'a sourceFix changed a fact, which a fix may never do (it repairs markdown structure only). Correct the fact in the English source instead',
    ]);
  });

  it('reads an Afrikaans source fix with Afrikaans markers, so an ordinal or a month change is refused', () => {
    const fix = (find: string, replace: string) => ({
      ...realEntry('core/start-here'),
      sourceFixes: [
        {
          lang: 'af' as const,
          find,
          replace,
          reason: 'A translation fix that changes a fact, which the guard must refuse.',
        },
      ],
    });
    const cases: [string, string, string][] = [
      ['Betaal teen die 7de van die maand.', 'die 7de', 'die 8ste'],
      ['Dien in teen 31 Augustus.', '31 Augustus', '31 September'],
      ['Dien in teen einde Augustus.', 'einde Augustus', 'einde September'],
    ];
    for (const [text, find, replace] of cases) {
      const issues = new IssueCollector();
      expect(applySourceFixes(text, fix(find, replace), 'af', afMarkers(), issues), text).toBe(
        text,
      );
      expect(codes(issues), text).toEqual(['source-fix-facts']);
    }
    // The English markers do not read `7de` or `Augustus`, which is why the language's own are passed.
    const english = new IssueCollector();
    applySourceFixes(cases[0]![0], fix('die 7de', 'die 8ste'), 'af', enMarkers(), english);
    expect(codes(english)).toEqual([]);
    // A structural fix in Afrikaans still applies.
    const structural = new IssueCollector();
    expect(
      applySourceFixes('Die 7de.\n3. Kies', fix('.\n3.', '.\n\n3.'), 'af', afMarkers(), structural),
    ).toBe('Die 7de.\n\n3. Kies');
    expect(codes(structural)).toEqual([]);
  });
});

describe('email addresses, bare domains and error locations', () => {
  it('keeps a bare email address as text and rejects an explicit mailto link', () => {
    const { parsed, issues } = parseMd(
      '# T\n\nEmail info@yourbusiness.co.za today.\n',
      realEntry('core/register'),
    );
    expect(codes(issues)).toEqual([]);
    expect(parsed.blocks[0]).toEqual(
      expect.objectContaining({
        kind: 'paragraph',
        c: [{ t: 'text', v: 'Email info@yourbusiness.co.za today.' }],
      }),
    );
    const explicit = parseMd(
      '# T\n\nWrite to [us](mailto:a@b.co.za).\n',
      realEntry('core/register'),
    );
    expect(explicit.issues.issues.map(formatIssue)).toEqual([
      '01 Core - applies to everyone/02-register.md:3: core/register:intro.1: unsupported-link: email links are not supported ("mailto:a@b.co.za"); write the address as plain text',
    ]);
  });

  it('fails on a bare domain that is not on the allow list, naming file and line', () => {
    const { parsed, issues } = parseMd(
      '# T\n\nBody.\n\nUse yourshop.co.za or cars.co.za as an example.\n',
      realEntry('core/register'),
    );
    expect(issues.issues.map(formatIssue)).toEqual([
      '01 Core - applies to everyone/02-register.md:5: core/register:intro.2: unknown-bare-domain: "yourshop.co.za" would become a link to yourshop.co.za. Add a real host to linkify.allowDomains, or an example name to linkify.ignoreDomains, in docs.meta.json',
    ]);
    expect(parsed.bareDomains).toEqual(['yourshop.co.za', 'cars.co.za']);
  });

  it('names the file and line for structural errors', () => {
    const { issues } = parseMd(
      '# T\n\nText.\n\n<div>html</div>\n',
      realEntry('core/register'),
      'en',
    );
    expect(issues.issues.map(formatIssue)).toEqual([
      '01 Core - applies to everyone/02-register.md:5: core/register:intro: unsupported-block: unsupported markdown node "html"',
    ]);
  });
});
